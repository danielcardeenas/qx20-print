"""Extract localizable strings with the Swift compiler, check the Spanish
translation covers them, and write Resources/{en,es}.lproj.

    python3 scripts/localize.py          # fails if a translation is missing
"""
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from es_translations import ES, INFO_PLIST_ES  # noqa: E402

FORMAT = re.compile(r"%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?(?:ll|l|h)?[@dDuUxXoOfeEgGcCsSaAp]")


def extract_keys():
    out = tempfile.mkdtemp()
    subprocess.run(["swift", "build", "-c", "debug", "--product", "QX20Print",
                    "-Xswiftc", "-emit-localized-strings",
                    "-Xswiftc", "-emit-localized-strings-path", "-Xswiftc", out],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    keys = set()
    for f in glob.glob(os.path.join(out, "*.stringsdata")):
        for entries in json.load(open(f)).get("tables", {}).values():
            keys.update(e["key"] for e in entries)
    return keys


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_strings(path, pairs, header):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"/* {header} — generated by scripts/localize.py */\n\n")
        for k in sorted(pairs):
            f.write(f'"{escape(k)}" = "{escape(pairs[k])}";\n')


def main():
    keys = extract_keys()
    missing = sorted(k for k in keys if k not in ES)
    unused = sorted(k for k in ES if k not in keys)
    bad = sorted(k for k in keys & ES.keys() if FORMAT.findall(k) != FORMAT.findall(ES[k]))
    for k in missing:
        print(f"MISSING translation: {k!r}")
    for k in bad:
        print(f"FORMAT mismatch: {k!r} -> {ES[k]!r}")
    for k in unused:
        print(f"unused translation (ignored): {k!r}")
    if missing or bad:
        sys.exit(1)

    res = os.path.join(ROOT, "Resources")
    write_strings(os.path.join(res, "es.lproj", "Localizable.strings"), {k: ES[k] for k in keys}, "Spanish")
    write_strings(os.path.join(res, "es.lproj", "InfoPlist.strings"), INFO_PLIST_ES, "Spanish Info.plist")
    # English is the development language: keys are the English text.
    write_strings(os.path.join(res, "en.lproj", "Localizable.strings"), {k: k for k in keys}, "English")
    print(f"{len(keys)} strings: es.lproj and en.lproj written")


if __name__ == "__main__":
    main()
